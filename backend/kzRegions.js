const CITY_TO_REGION = {};
for (const [regionId, cities] of Object.entries(CITIES_BY_REGION)) {
  for (const city of cities) {
    const key = normalizeCity(city);
    if (!key) continue;
    // Уточнения в скобках ("абай (вко)") нужны только чтобы не потерять город из виду в списке;
    // ключом должно быть чистое название, а спорные дубли разруливаются порядком: побеждает
    // первый, кто занял ключ, поэтому области перечислены выше в алфавитном порядке, а
    // город-омоним с уточнением просто не перетирает уже занятый ключ.
    const clean = key.replace(/\s*\(.*\)\s*$/, '');
    if (!CITY_TO_REGION[clean]) CITY_TO_REGION[clean] = regionId;
  }
}

