// Казахские буквы приводим к русским аналогам — Kaspi присылает названия и так, и так
// ("Ақтөбе" и "Актобе" должны попасть в одну строку таблицы).
const KAZAKH_LETTERS = {
  ә: 'а', ғ: 'г', қ: 'к', ң: 'н', ө: 'о', ұ: 'у', ү: 'у', һ: 'х', і: 'и', ё: 'е',
};

// Приставки вида "г.", "город", "с.", "село", "пос." — Kaspi присылает их не всегда,
// поэтому убираем, чтобы "г. Актобе" и "Актобе" не стали двумя разными городами.
const PREFIXES = /^(г|гор|город|қала|с|село|c|ст|станция|п|пос|посёлок|поселок|аул|а|мкр|район|р-н)\s*\.?\s+/i;

function normalizeCity(raw) {
  if (!raw) return '';
  let s = String(raw).trim().toLowerCase();
  s = s.replace(/[«»"']/g, '');
  s = s.split('').map((ch) => KAZAKH_LETTERS[ch] || ch).join('');
  // приставку могли написать и дважды ("г. с. Явленка") — снимаем, пока снимается
  let prev;
  do { prev = s; s = s.replace(PREFIXES, ''); } while (s !== prev);
  s = s.replace(/\s+/g, ' ').replace(/[–—]/g, '-').trim();
  return s;
}

